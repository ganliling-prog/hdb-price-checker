import { HdbTransaction } from '../types/housing';

export const SQM_TO_SQFT = 10.7639;

export function formatHdbTransaction(raw: {
  _id: number | string;
  month: string;
  town: any;
  flat_type: any;
  block: string;
  street_name: string;
  storey_range: any;
  floor_area_sqm: number | string;
  flat_model: string;
  lease_commence_date: number | string;
  remaining_lease: string;
  resale_price: number | string;
}): HdbTransaction {
  const sqm = Number(raw.floor_area_sqm);
  const price = Number(raw.resale_price);
  const sqft = Math.round(sqm * SQM_TO_SQFT);
  const psf = Math.round(price / (sqft || 1));
  const psm = Math.round(price / (sqm || 1));

  return {
    _id: raw._id,
    month: String(raw.month),
    town: raw.town,
    flat_type: raw.flat_type,
    block: String(raw.block),
    street_name: String(raw.street_name),
    storey_range: raw.storey_range,
    floor_area_sqm: sqm,
    flat_model: String(raw.flat_model),
    lease_commence_date: Number(raw.lease_commence_date),
    remaining_lease: String(raw.remaining_lease),
    resale_price: price,
    floor_area_sqft: sqft,
    price_per_sqft: psf,
    price_per_sqm: psm,
  };
}

